"""Regenerate the Caddy handle_errors block from web/offline.html.

When the app is off, nothing of the app is reachable — so the "not running"
page has to be served by the reverse proxy. Keeping the page in the repo and
generating the proxy snippet from it means the two cannot drift apart.

    .venv/Scripts/python.exe tools/make_offline_block.py
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PAGE = REPO / "vrc_parameter_relay" / "web" / "offline.html"
OUT = REPO / "docs" / "caddy-offline-block.txt"


def main() -> None:
    html = PAGE.read_text("utf-8").rstrip("\n")
    if "`" in html:
        raise SystemExit("offline.html contains a backtick — Caddy quotes "
                         "the respond body with one, so it must not appear")
    block = (
        "    # Served when the app on the PC is not reachable (it is off, or\n"
        "    # the machine is). Only Caddy can answer then, so the page lives\n"
        "    # here. Source of truth: vrc_parameter_relay/web/offline.html in\n"
        "    # the repo, regenerated by tools/make_offline_block.py — edit there.\n"
        "    handle_errors {\n"
        '        header Content-Type "text/html; charset=utf-8"\n'
        "        header Retry-After 15\n"
        "        respond `" + html + "` 503\n"
        "    }\n")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(block, "utf-8", newline="\n")
    print(f"{OUT.relative_to(REPO)} — {len(block.splitlines())} lines")


if __name__ == "__main__":
    main()
